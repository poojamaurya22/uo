"""Write hardware/params.scad from RobotSpec, so the printed robot matches the simulated one.

    python scripts/gen_scad_params.py
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from petsim.robot import RobotSpec  # noqa: E402

OUT = os.path.join(ROOT, "hardware", "params.scad")


def render():
    s = RobotSpec()
    mm = lambda metres: round(metres * 1000, 2)  # noqa: E731
    values = {
        "body_l": mm(2 * s.body_half[0]),
        "body_w": mm(2 * s.body_half[1]),
        "body_h": mm(2 * s.body_half[2]),
        "clearance": mm(s.clearance),
        "wheel_r": mm(s.wheel_radius),
        "wheel_spacing_nominal": mm(s.wheel_spacing),
        "track_w": mm(2 * s.track_half_width),
        "track_gap": mm(s.track_gap),
        "neck_x": mm(-0.3 * s.body_half[0]),
        "eye_r": mm(s.eye_radius),
        "eye_len": mm(2 * s.eye_half_length),
        "eye_y": mm(s.eye_radius + 0.004),
        "eye_x": 10.0,
        "eye_centre_above_lid": mm(s.neck_height + 0.6 * s.eye_radius),
        "tof_z": mm(s.body_half[2] - 0.35 * s.body_half[2]),
        "side_tof_yaw": s.side_tof_yaw_deg,
        "side_tof_z": mm(s.body_half[2] - 0.01),
        "cliff_reach": 30.0,
    }
    lines = ["// Generated by scripts/gen_scad_params.py from petsim.robot.RobotSpec. Do not edit.",
             "// All values in millimetres / degrees."]
    lines += [f"{k} = {v};" for k, v in values.items()]
    return "\n".join(lines) + "\n"


def main():
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(render())
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
